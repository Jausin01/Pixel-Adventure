namespace MobileRpg
{
    /// <summary>
    /// The families of weapons that can carry skills. Skills belong to a weapon class, not to a single weapon:
    /// every sword shares the sword skills. Append new values only.
    /// </summary>
    public enum WeaponClass
    {
        Sword = 0,
        Axe = 1,
        Spear = 2,
        Bow = 3,
        Dagger = 4,
        Hammer = 5,
        Staff = 6
    }
}
